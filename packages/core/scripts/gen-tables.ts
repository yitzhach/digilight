// Generates src/srgb-tables.ts (§5.10) and src/kelvin-tables.ts (§5.8). Run once:
//   node scripts/gen-tables.ts
// The outputs are committed; core never computes them at run time.
// Black-body route ported from v1 src/kelvin.js: kelvin -> CIE 1931 xy on the Planckian locus
// (Kim et al. cubic spline) -> XYZ (Y = 1) -> linear RGB, negative lobes clipped.

import { writeFileSync } from 'node:fs';

const here = new URL('../src/', import.meta.url);

// ---- sRGB transfer curve (shared by sRGB and Display P3)
const decode = (v: number) => (v <= 0.04045 ? v / 12.92 : Math.pow((v + 0.055) / 1.055, 2.4));
const DEC = Array.from({ length: 256 }, (_, i) => decode(i / 255));
DEC[0] = 0; DEC[255] = 1;
// Threshold i: the linear value whose continuous encoding is halfway between codes i and i+1.
const THR = Array.from({ length: 255 }, (_, i) => decode((i + 0.5) / 255));

writeFileSync(new URL('srgb-tables.ts', here), `// Generated by scripts/gen-tables.ts. Do not edit.
/** Linear value of each 8-bit code. */
export const DECODE: readonly number[] = [${DEC.join(', ')}];
/** Linear thresholds between neighbouring codes: code = number of thresholds <= value. */
export const THRESHOLDS: readonly number[] = [${THR.join(', ')}];
`);

// ---- black body
function planckianXY(kelvin: number): [number, number] {
  const T = Math.min(25000, Math.max(1667, kelvin));
  const t1 = 1e3 / T, t2 = 1e6 / (T * T), t3 = 1e9 / (T * T * T);
  const x = T <= 4000
    ? -0.2661239 * t3 - 0.2343589 * t2 + 0.8776956 * t1 + 0.179910
    : -3.0258469 * t3 + 2.1070379 * t2 + 0.2226347 * t1 + 0.240390;
  const x2 = x * x, x3 = x2 * x;
  const y = T <= 2222 ? -1.1063814 * x3 - 1.34811020 * x2 + 2.18555832 * x - 0.20219683
    : T <= 4000 ? -0.9549476 * x3 - 1.37418593 * x2 + 2.09137015 * x - 0.16748867
      : 3.0817580 * x3 - 5.87338670 * x2 + 3.75112997 * x - 0.37001483;
  return [x, y];
}
// CIE XYZ (D65) to linear RGB. sRGB: IEC 61966-2-1 (as v1). Display P3: SMPTE EG 432-1, D65.
const MATRIX = {
  srgb: [3.2404542, -1.5371385, -0.4985314, -0.9692660, 1.8760108, 0.0415560, 0.0556434, -0.2040259, 1.0572252],
  'display-p3': [2.4934969, -0.9313836, -0.4027108, -0.8294890, 1.7626641, 0.0236247, 0.0358458, -0.0761724, 0.9568845],
};
const luma = (c: number[]) => 0.2126 * c[0]! + 0.7152 * c[1]! + 0.0722 * c[2]!;
function blackBody(kelvin: number, m: number[]): number[] {
  const [x, y] = planckianXY(kelvin);
  const X = x / y, Y = 1, Z = (1 - x - y) / y;
  return [0, 1, 2].map((i) => Math.max(0, m[i * 3]! * X + m[i * 3 + 1]! * Y + m[i * 3 + 2]! * Z));
}
function table(m: number[]): number[] {
  const white = blackBody(6500, m), out: number[] = [];
  for (let K = 1500; K <= 12000; K += 100) {
    if (K === 6500) { out.push(1, 1, 1); continue; }
    const c = blackBody(K, m).map((v, i) => v / white[i]!), l = luma(c);
    out.push(...c.map((v) => v / l));
  }
  return out;
}

writeFileSync(new URL('kelvin-tables.ts', here), `// Generated by scripts/gen-tables.ts. Do not edit.
/** colour(K) for K = 1500, 1600, ... 12000: linear r, g, b per entry, 6500 K = (1, 1, 1), luma 1. */
export const KELVIN_MIN = 1500, KELVIN_STEP = 100;
export const KELVIN_SRGB: readonly number[] = [${table(MATRIX.srgb).join(', ')}];
export const KELVIN_P3: readonly number[] = [${table(MATRIX['display-p3']).join(', ')}];
`);
console.log('wrote src/srgb-tables.ts, src/kelvin-tables.ts');
